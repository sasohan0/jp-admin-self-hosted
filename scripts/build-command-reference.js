const fs = require('fs');
const path = require('path');
const { catalogEntries } = require('../help');

function escapeCell(value) {
  return String(value || '')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, ' ');
}

const entries = catalogEntries();
const groups = [];
for (const entry of entries) {
  let group = groups.find(item => item.category === entry.category);
  if (!group) {
    group = { category: entry.category, section: entry.section, entries: [] };
    groups.push(group);
  }
  group.entries.push(entry);
}

const lines = [
  '# JP ADMIN mentor command reference',
  '',
  `This file lists all ${entries.length} commands in the bot's authoritative \`help.js\` catalog. It is generated by \`npm run docs:commands\`; do not edit it by hand.`,
  '',
  'Run supervisor commands in the private `#bot-admin` unless a row explicitly names a student channel. Commands that announce, mention students, change status, or write data should be previewed and used deliberately.',
  '',
];

for (const group of groups) {
  lines.push(`## ${group.section}`, '', '| Command | What it does |', '| --- | --- |');
  for (const entry of group.entries) {
    lines.push(`| \`${escapeCell(entry.command)}\` | ${escapeCell(entry.description)} |`);
  }
  lines.push('');
}

const output = path.join(__dirname, '..', 'MENTOR_COMMAND_REFERENCE.md');
fs.writeFileSync(output, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${path.basename(output)} with ${entries.length} commands.`);
